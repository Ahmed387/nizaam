CREATE OR REPLACE FUNCTION public.disburse_employee_advance(
  p_employee_id uuid,
  p_amount numeric,
  p_monthly_deduct numeric,
  p_reason text DEFAULT NULL,
  p_payment_method text DEFAULT 'cash',
  p_reference_number text DEFAULT NULL,
  p_transfer_to_account text DEFAULT NULL,
  p_transfer_from_account text DEFAULT NULL,
  p_fee_amount numeric DEFAULT 0
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_emp record;
  v_adv_id uuid;
  v_tr_id uuid;
  v_fee_id uuid;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'غير مصرح'; END IF;
  IF coalesce(p_amount,0) <= 0 THEN RAISE EXCEPTION 'أدخل مبلغ السلفة'; END IF;
  IF coalesce(p_monthly_deduct,0) <= 0 THEN RAISE EXCEPTION 'أدخل قيمة الخصم الشهري'; END IF;
  IF coalesce(p_fee_amount,0) < 0 THEN RAISE EXCEPTION 'عمولة غير صالحة'; END IF;

  SELECT id, name, branch_id, tenant_id INTO v_emp FROM employees WHERE id = p_employee_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'الموظف غير موجود'; END IF;
  IF v_emp.tenant_id IS DISTINCT FROM current_tenant_id() AND NOT is_super_admin(v_uid) THEN RAISE EXCEPTION 'غير مصرح'; END IF;
  IF NOT (is_admin(v_uid) OR user_can_write_branch(v_uid, v_emp.branch_id)) THEN RAISE EXCEPTION 'لا تملك صلاحية الصرف من خزينة هذا الفرع'; END IF;

  INSERT INTO advances (employee_id, amount, monthly_deduct, remaining, reason, tenant_id)
  VALUES (v_emp.id, p_amount, p_monthly_deduct, p_amount, nullif(p_reason,''), v_emp.tenant_id)
  RETURNING id INTO v_adv_id;

  -- Treasury balance guard (trg_check_treasury_balance) raises on insufficient funds → whole call rolls back.
  -- Payment voucher is generated by trg_treasury_to_voucher in the same transaction.
  INSERT INTO treasury (tenant_id, branch_id, type, category, amount, description, reference_id, created_by,
                        payment_method, reference_number, transfer_to_account, transfer_from_account)
  VALUES (v_emp.tenant_id, v_emp.branch_id, 'expense', 'advance', p_amount, 'سلفة - ' || v_emp.name, v_adv_id, v_uid,
          coalesce(p_payment_method,'cash'), p_reference_number, p_transfer_to_account, p_transfer_from_account)
  RETURNING id INTO v_tr_id;

  IF coalesce(p_fee_amount,0) > 0 THEN
    INSERT INTO treasury (tenant_id, branch_id, type, category, amount, description, reference_id, created_by, is_fee, payment_method)
    VALUES (v_emp.tenant_id, v_emp.branch_id, 'expense', 'transfer_fee', p_fee_amount,
            'عمولة ' || coalesce(p_payment_method,'') || ' - سلفة ' || v_emp.name, v_adv_id, v_uid, true, p_payment_method)
    RETURNING id INTO v_fee_id;
  END IF;

  RETURN jsonb_build_object('advance_id', v_adv_id, 'treasury_id', v_tr_id, 'fee_treasury_id', v_fee_id,
    'voucher_number', (SELECT voucher_number FROM vouchers WHERE treasury_id = v_tr_id LIMIT 1));
END;
$$;

REVOKE ALL ON FUNCTION public.disburse_employee_advance(uuid, numeric, numeric, text, text, text, text, text, numeric) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.disburse_employee_advance(uuid, numeric, numeric, text, text, text, text, text, numeric) TO authenticated;

-- Treasury is fed only by approved SECURITY DEFINER functions and official vouchers.
REVOKE INSERT ON public.treasury FROM authenticated, anon;
COMMENT ON TABLE public.treasury IS 'Write-protected: INSERT only via SECURITY DEFINER RPCs (no direct client inserts).';